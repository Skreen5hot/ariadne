"""Render docs/05-evidence-audit/audit.md from the inventory, the spec index and the evidence records.

Usage:  python tools/render_audit.py            (writes audit.md)
        python tools/render_audit.py --check    (exit 1 if audit.md is stale)

The rendered file is generated; never edit it by hand. Every level in it is computed by
tools/evidence_audit.py from evidence/*.json. Staleness is measured against the most recent
collection in the set, so the file is reproducible from the committed records.
"""
from __future__ import annotations

import sys
from collections import Counter
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from evidence_audit import (LEVELS, OUT, ROOT, consumers, label, load_evidence,  # noqa: E402
                            load_inventory, load_spec_index, repo_level, spec_level)

MATURE_WORDS = ("final", "hardened", "stable", "release candidate", "ready", "normative", "governance-ready", "candidate")


def esc(s: object) -> str:
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ").strip()


def render(inv: dict, specs, evidence: dict[str, dict]) -> str:
    as_of = max((datetime.fromisoformat(r["collected_at"]).date() for r in evidence.values()), default=None)
    repos = [r["name"] for r in inv.get("repos", [])]
    rlevels = {n: repo_level(n, evidence, as_of) for n in repos}
    buildable_layers = set(inv.get("buildable_layers") or [])
    exempt = {e["spec"]: e["reason"] for e in inv.get("not_buildable") or []}
    buildable = [s for s in specs if s.layer in buildable_layers and s.name not in exempt]
    slevels = {s.name: spec_level(s.name, inv, evidence, as_of) for s in buildable}

    L: list[str] = []
    L.append("# Evidence audit (rendered)")
    L.append("")
    L.append("Generated by `tools/render_audit.py` from `inventory.yaml`, `evidence/*.json` and "
             "`docs/00-foundation/spec-index.md`. Do not edit by hand. Every level is computed from "
             "collected evidence; none is asserted. See README.md for the ladder and how to refresh.")
    L.append("")
    L.append(f"Evidence as of: {as_of or 'never collected'}. Repositories inventoried: {len(repos)}, "
             f"collected: {sum(1 for n in repos if n in evidence)}.")
    L.append("")

    # ---- headline
    dist = Counter(lv for lv, _ in slevels.values())
    mature = [s for s in buildable if any(w in s.status.lower() for w in MATURE_WORDS)]
    mature_unbuilt = [s for s in mature if slevels[s.name][0] == 0]
    L.append("## Headline")
    L.append("")
    unmapped = sum(1 for r in inv.get("repos", []) if not r.get("implements"))
    L.append(f"> Read L0 with care: it means no inventoried repository is mapped to the spec. With "
             f"{len(repos)} repositories inventoried ({unmapped} not yet mapped to any spec), some L0 specs "
             "may have code in a repository the audit has not seen. Run `tools/sync_inventory.py` and map "
             "the repositories before treating L0 as \"nothing built\".")
    L.append("")
    L.append(f"- Buildable specifications in the index: **{len(buildable)}**.")
    for i, name in enumerate(LEVELS):
        L.append(f"- {name}: **{dist.get(i, 0)}**")
    L.append(f"- Specifications whose document status claims maturity (Final, Hardened, Stable, Candidate, Ready, Normative) "
             f"but have no mapped code: **{len(mature_unbuilt)} of {len(mature)}**.")
    L.append("")

    # ---- repositories
    L.append("## Repositories")
    L.append("")
    L.append("| Repository | Evidence level | Why | Last commit | Tests run | Used by | Implements |")
    L.append("| --- | --- | --- | --- | --- | --- | --- |")
    order = sorted(repos, key=lambda n: (-rlevels[n].level, n.lower()))
    impl = {r["name"]: r.get("implements") or [] for r in inv.get("repos", [])}
    users = consumers(evidence)
    for n in order:
        lv = rlevels[n]
        rec = evidence.get(n) or {}
        head = (rec.get("head") or {}).get("date", "")[:10]
        run = rec.get("run")
        run_s = "not run" if not run else f"exit {run['exit_code']} at {run['sha'][:7]}, {run['at'][:10]}"
        L.append(f"| [{n}]({rec.get('url', '')}) | {label(lv)} | {esc('; '.join(lv.why))} | {head} | {esc(run_s)} | "
                 f"{esc(', '.join(users.get(n, [])) or '—')} | {esc(', '.join(impl[n]) or 'no indexed spec')} |")
    L.append("")

    # ---- specs
    L.append("## Buildable specifications")
    L.append("")
    L.append("Document status is copied from spec-index.md. Evidence level is computed. The gap between "
             "the two columns is the point of this table.")
    L.append("")
    L.append("| Specification | Layer | Version | Document status | Evidence level | Repositories |")
    L.append("| --- | --- | --- | --- | --- | --- |")
    for s in sorted(buildable, key=lambda s: (-slevels[s.name][0], s.layer, s.name.lower())):
        lv, reps = slevels[s.name]
        rep_s = ", ".join(f"{r.repo} ({label(r)})" for r in reps) or "none mapped"
        L.append(f"| {esc(s.name)} | {s.layer} | {esc(s.version)} | {esc(s.status)} | {LEVELS[lv]} | {esc(rep_s)} |")
    L.append("")

    # ---- unindexed
    unindexed = [n for n in order if not impl[n]]
    if unindexed:
        L.append("## Repositories with no indexed specification")
        L.append("")
        L.append("Code that exists without a spec-index entry. Either the index is missing something real, "
                 "or the repository is not part of the ecosystem the index describes.")
        L.append("")
        for n in unindexed:
            L.append(f"- {n}: {label(rlevels[n])}")
        L.append("")

    # ---- not laddered
    others = [s for s in specs if s.layer not in buildable_layers]
    L.append("## Not laddered")
    L.append("")
    L.append(f"{len(others)} entries in the Philosophy, Foundation and Communications layers are arguments and records; "
             "they are not expected to run and are not scored here.")
    for name, reason in exempt.items():
        L.append(f"- {name}: {reason}")
    L.append("")
    return "\n".join(L)


def main(argv: list[str]) -> int:
    text = render(load_inventory(), load_spec_index(), load_evidence())
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("audit.md is stale; run python tools/render_audit.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
